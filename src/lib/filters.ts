import type { IndexItem } from './types'

export type SubFilter = { id: string; label: string; test: (r: IndexItem, t: string) => boolean }
// t = tytuł + składniki + opis, małymi literami i bez polskich znaków (patrz fold)
const rx = (p: string) => new RegExp(p)
const has = (p: string): SubFilter['test'] => { const r = rx(p); return (_r, t) => r.test(t) }
const tag = (g: string): SubFilter['test'] => r => r.tags.includes(g)
const fast = (m: number): SubFilter['test'] => r => r.min <= m
const f = (id: string, label: string, test: SubFilter['test']): SubFilter => ({ id, label, test })

